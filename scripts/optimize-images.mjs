import { readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const imagesDir = path.resolve("public/images");
const outDir = path.join(imagesDir, "opt");
const manifestPath = path.resolve("app/lib/image-variants.ts");

const files = (await readdir(imagesDir))
  .filter((file) => file.endsWith(".jpg"))
  .sort();

await mkdir(outDir, { recursive: true });

/** @type {string[]} */
const entries = [];

for (const file of files) {
  const base = file.slice(0, -4);
  const input = path.join(imagesDir, file);
  const meta = await sharp(input).metadata();
  let width = meta.width ?? 0;
  let height = meta.height ?? 0;
  if ((meta.orientation ?? 1) >= 5) {
    [width, height] = [height, width];
  }

  const requested = base === "hero" ? [960, 1600, 1920] : [960, 1600];
  /** @type {{ width: number; name: string }[]} */
  const variants = [];

  for (const target of requested) {
    const outputWidth = Math.min(target, width);
    if (outputWidth <= 0 || variants.some((variant) => variant.width === outputWidth)) {
      continue;
    }
    const name = `${base}-${outputWidth}.jpg`;
    await sharp(input)
      .rotate()
      .resize({ width: outputWidth, withoutEnlargement: true })
      .jpeg({ quality: 75, mozjpeg: true })
      .toFile(path.join(outDir, name));
    variants.push({ width: outputWidth, name });
  }

  const srcSet = variants
    .map((variant) => `/images/opt/${variant.name} ${variant.width}w`)
    .join(", ");
  const smallest = variants[0];
  entries.push(
    `  ${JSON.stringify(`/images/${file}`)}: { src: ${JSON.stringify(`/images/opt/${smallest.name}`)}, srcSet: ${JSON.stringify(srcSet)} },`,
  );
}

const manifest = `/** Generated by scripts/optimize-images.mjs. Do not edit. */
export const imageVariants: Record<string, { src: string; srcSet: string }> = {
${entries.join("\n")}
};
`;

await writeFile(manifestPath, manifest);
console.log(`Wrote ${files.length} images and ${manifestPath}`);
